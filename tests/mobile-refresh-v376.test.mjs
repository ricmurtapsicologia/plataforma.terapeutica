import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const version=read('assets/js/version.js').match(/APP_VERSION='([^']+)'/)?.[1];
const index=read('index.html');
const main=read('assets/js/main-v250.js');
const cleanup=read('assets/js/legacy-sw-cleanup-v240.js');
const manifest=read('assets/js/core/clinical-runtime-manifest-v376.mjs');
assert.equal(version,'3.7.6');
assert.ok(index.includes('content="'+version+'-main-v250"'));
assert.ok(index.includes('main-v250.js?v='+version));
assert.ok(index.includes('app.css?v='+version));
assert.ok(index.includes('manifest.webmanifest?v='+version));
assert.ok(main.includes("__rmEntrypointVersion='"+version+"-main-v250'"));
assert.ok(main.includes('bootstrap-v240.js?v='+version));
assert.ok(main.includes('legacy-sw-cleanup-v240.js?v='+version));
assert.ok(manifest.includes("RUNTIME_MANIFEST_VERSION='"+version+"'"));
assert.ok(cleanup.includes('registration.scope===scope'));
assert.ok(cleanup.includes('registration.unregister()'));
assert.doesNotMatch(cleanup,/indexedDB\.deleteDatabase|localStorage\.clear|caches\.delete/);
console.log('MOBILE_REFRESH_V376_PASS');
